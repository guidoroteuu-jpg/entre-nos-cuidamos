const languageNames: Record<Language, string> = {
  "pt-BR": "PT",
  en: "EN",
  es: "ES",
};

const getInitialLanguage = (): Language => {
  if (typeof window === "undefined") return "pt-BR";
  const stored = localStorage.getItem(languageStorageKey) as Language | null;
  if (stored && stored in translations) return stored;
  const browserLanguage = navigator.language.toLowerCase();
  if (browserLanguage.startsWith("en")) return "en";
  if (browserLanguage.startsWith("es")) return "es";
  return "pt-BR";
};

const I18nContext = createContext<{
  language: Language;
  languages: typeof languageNames;
  setLanguage: (language: Language) => void;
  t: (key: TranslationKey) => string;
} | null>(null);

export const I18nProvider = ({ children }: { children: React.ReactNode }) => {
  const [language, setLanguageState] = useState<Language>("pt-BR");

  useEffect(() => {
    const detected = getInitialLanguage();
    if (detected !== language) setLanguageState(detected);
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  const setLanguage = (nextLanguage: Language) => {
    localStorage.setItem(languageStorageKey, nextLanguage);
    setLanguageState(nextLanguage);
  };

  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);


  const value = useMemo(
    () => ({
      language,
      languages: languageNames,
      setLanguage,
      t: (key: TranslationKey) => translations[language][key] || translations["pt-BR"][key],
    }),
    [language],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
};

export const useI18n = () => {
  const context = useContext(I18nContext);
  if (!context) throw new Error("useI18n must be used within I18nProvider");
  return context;
};

export type { Language, TranslationKey };